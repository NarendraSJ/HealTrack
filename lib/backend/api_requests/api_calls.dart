  }) async {
    final ffApiRequestBody = '''
{
  "input": [
    ${hr},
    ${spo2},
    ${temp},
    ${hum}
  ]
}''';
    return ApiManager.instance.makeApiCall(
      callName: 'getSleep',
      apiUrl: 'https://sleep-predictor-api.onrender.com/predict',
      callType: ApiCallType.POST,
      headers: {},
      params: {},
      body: ffApiRequestBody,
      bodyType: BodyType.JSON,
      returnBody: true,
      encodeBodyUtf8: false,
      decodeUtf8: false,
      cache: false,
      isStreamingApi: false,
      alwaysAllowBody: false,
    );
  }

  static String? apiResult(dynamic response) => castToType<String>(getJsonField(
        response,
        r'''$.result''',
      ));
}

